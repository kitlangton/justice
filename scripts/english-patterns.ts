// Regenerates src/english-patterns.ts from hyph-utf8's American English patterns:
//   bun scripts/english-patterns.ts
const url = "https://raw.githubusercontent.com/hyphenation/tex-hyphen/master/hyph-utf8/tex/generic/hyph-utf8/patterns/tex/hyph-en-us.tex";
const tex = await (await fetch(url)).text();
const block = (name: string) => tex.match(new RegExp(`\\\\${name}\\{([^}]*)\\}`))![1].replace(/%.*$/gm, "").trim().split(/\s+/);
const header = tex.split("\n").filter(line => line.startsWith("% ")).slice(0, 16).map(line => ` *${line.slice(1)}`).join("\n");
const source = `/*! Generated by scripts/english-patterns.ts from hyph-utf8's hyph-en-us.tex.
${header}
 */
export const patterns: string = ${JSON.stringify(block("patterns").sort().join(" "))};
export const exceptions: string = ${JSON.stringify(block("hyphenation").join(" "))};
`;
await Bun.write(new URL("../src/english-patterns.ts", import.meta.url), source);
console.log(`${block("patterns").length} patterns, ${block("hyphenation").length} exceptions`);
